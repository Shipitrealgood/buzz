//! Tests for `buzz-provision retire` (T5 host half) that need no relay and
//! no systemd: state detection, fail-closed config validation, dry-run
//! no-touch guarantees, converged re-runs, and the no-secret-leak scan.
//!
//! The relay-interacting lifecycle (leaves land, 10100 tombstoned, kind:0
//! untouched, owner 9035 accepted) lives in `e2e_local_relay.rs`.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use nostr::Keys;

fn bin() -> &'static str {
    env!("CARGO_BIN_EXE_buzz-provision")
}

fn stdout(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned()
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

fn mode_of(path: &Path) -> u32 {
    fs::metadata(path).unwrap().permissions().mode() & 0o7777
}

/// Assert no 16-char window of a 64-char secret appears in any surface.
fn assert_no_secret_leak(secret_hex: &str, surfaces: &[&str]) {
    assert_eq!(secret_hex.len(), 64);
    for start in 0..=(64 - 16) {
        let window = &secret_hex[start..start + 16];
        for surface in surfaces {
            assert!(
                !surface.contains(window),
                "secret substring leaked into output (window at offset {start})"
            );
        }
    }
}

struct Ctx {
    #[allow(dead_code)]
    tmp: tempfile::TempDir,
    config_dir: PathBuf,
    env_dir: PathBuf,
}

fn ctx() -> Ctx {
    let tmp = tempfile::tempdir().unwrap();
    let config_dir = tmp.path().join("cfg");
    let env_dir = tmp.path().join("env");
    fs::create_dir_all(&env_dir).unwrap();
    Ctx {
        tmp,
        config_dir,
        env_dir,
    }
}

fn run_retire(ctx: &Ctx, name: &str, extra: &[&str]) -> Output {
    Command::new(bin())
        .args(["retire", name, "--no-systemd"])
        .args(extra)
        .arg("--config-dir")
        .arg(&ctx.config_dir)
        .arg("--env-dir")
        .arg(&ctx.env_dir)
        .output()
        .expect("spawn buzz-provision retire")
}

/// Provisioned-state fixture: credential + secret-free env file + .pub
/// marker, exactly the files `provision agent` leaves behind. Returns
/// (agent keys, owner keys).
fn seed_provisioned(ctx: &Ctx, name: &str, relay_url: Option<&str>) -> (Keys, Keys) {
    let agent = Keys::generate();
    let owner = Keys::generate();
    let creds = ctx.config_dir.join("creds");
    fs::create_dir_all(&creds).unwrap();
    let cred_path = creds.join(format!("{name}.nsec"));
    fs::write(&cred_path, agent.secret_key().to_secret_hex()).unwrap();
    fs::set_permissions(&cred_path, fs::Permissions::from_mode(0o600)).unwrap();

    let attestation = buzz_sdk::nip_oa::compute_auth_tag(&owner, &agent.public_key(), "").unwrap();
    let mut env = String::new();
    env.push_str(&format!(
        "# {name} agent — generated by buzz-provision agent; DO NOT add secrets here.\n"
    ));
    env.push_str(&format!(
        "# agent pubkey: {}\n",
        agent.public_key().to_hex()
    ));
    env.push_str(&format!(
        "# owner pubkey: {}\n",
        owner.public_key().to_hex()
    ));
    if let Some(url) = relay_url {
        env.push_str(&format!("BUZZ_RELAY_URL={url}\n"));
    }
    env.push_str("BUZZ_ACP_AGENT_COMMAND=/usr/bin/true\n");
    env.push_str(&format!("BUZZ_AUTH_TAG={attestation}\n"));
    let env_path = ctx.env_dir.join(format!("{name}.env"));
    fs::write(&env_path, env).unwrap();
    fs::set_permissions(&env_path, fs::Permissions::from_mode(0o600)).unwrap();
    fs::write(
        ctx.env_dir.join(format!("{name}.pub")),
        format!("{}\n", agent.public_key().to_hex()),
    )
    .unwrap();
    (agent, owner)
}

#[test]
fn unknown_name_is_refused_as_probable_typo() {
    let ctx = ctx();
    let out = run_retire(&ctx, "no-such-agent", &[]);
    assert!(!out.status.success());
    assert!(
        stderr(&out).contains("no trace of agent"),
        "unexpected: {}",
        stderr(&out)
    );
}

#[test]
fn missing_relay_url_fails_closed_before_any_change() {
    let ctx = ctx();
    let (agent, _) = seed_provisioned(&ctx, "teacup", None);
    let out = run_retire(&ctx, "teacup", &[]);
    assert!(!out.status.success());
    assert!(stderr(&out).contains("no relay URL"), "{}", stderr(&out));
    // Nothing moved: credential + env + pub all intact.
    assert!(ctx.config_dir.join("creds/teacup.nsec").exists());
    assert!(ctx.env_dir.join("teacup.env").exists());
    assert!(ctx.env_dir.join("teacup.pub").exists());
    assert_no_secret_leak(
        &agent.secret_key().to_secret_hex(),
        &[&stdout(&out), &stderr(&out)],
    );
}

#[test]
fn missing_auth_tag_fails_closed_with_recovery_hint() {
    let ctx = ctx();
    let (_agent, _) = seed_provisioned(&ctx, "teacup", Some("ws://127.0.0.1:1"));
    // Strip the attestation line from the env file.
    let env_path = ctx.env_dir.join("teacup.env");
    let stripped: String = fs::read_to_string(&env_path)
        .unwrap()
        .lines()
        .filter(|l| !l.starts_with("BUZZ_AUTH_TAG="))
        .map(|l| format!("{l}\n"))
        .collect();
    fs::write(&env_path, stripped).unwrap();

    let out = run_retire(&ctx, "teacup", &[]);
    assert!(!out.status.success());
    assert!(stderr(&out).contains("BUZZ_AUTH_TAG"), "{}", stderr(&out));
    assert!(ctx.config_dir.join("creds/teacup.nsec").exists());
}

#[test]
fn credential_env_pubkey_mismatch_is_refused() {
    let ctx = ctx();
    let (_agent, _) = seed_provisioned(&ctx, "teacup", Some("ws://127.0.0.1:1"));
    // Swap in a DIFFERENT identity's credential under the same name.
    let impostor = Keys::generate();
    fs::write(
        ctx.config_dir.join("creds/teacup.nsec"),
        impostor.secret_key().to_secret_hex(),
    )
    .unwrap();
    let out = run_retire(&ctx, "teacup", &[]);
    assert!(!out.status.success());
    assert!(
        stderr(&out).contains("mismatched identity"),
        "{}",
        stderr(&out)
    );
    // Refusal happens before any teardown: everything intact.
    assert!(ctx.config_dir.join("creds/teacup.nsec").exists());
    assert!(ctx.env_dir.join("teacup.env").exists());
    assert_no_secret_leak(
        &impostor.secret_key().to_secret_hex(),
        &[&stdout(&out), &stderr(&out)],
    );
}

#[test]
fn dry_run_touches_nothing_and_prints_owner_command() {
    let ctx = ctx();
    // Unreachable relay: dry-run must fail-soft on discovery and still plan.
    let (agent, _) = seed_provisioned(&ctx, "teacup", Some("ws://127.0.0.1:1"));
    let env_before = fs::read_to_string(ctx.env_dir.join("teacup.env")).unwrap();

    let out = run_retire(&ctx, "teacup", &["--dry-run"]);
    let so = stdout(&out);
    let se = stderr(&out);
    assert!(out.status.success(), "dry-run must succeed: {se}");
    assert!(so.contains("DRY RUN"), "{so}");
    assert!(
        se.contains("membership discovery failed"),
        "must surface the discovery fail-soft: {se}"
    );
    // The tombstone is still planned.
    assert!(so.contains("kind:10100 tombstone"), "{so}");
    // The exact owner-half command is printed (keygen UX pattern).
    assert!(
        so.contains(&format!(
            "buzz-mint retire --agent {} --relay-url ws://127.0.0.1:1",
            agent.public_key().to_hex()
        )),
        "{so}"
    );
    // NOTHING moved.
    assert!(ctx.config_dir.join("creds/teacup.nsec").exists());
    assert!(ctx.env_dir.join("teacup.pub").exists());
    assert_eq!(
        fs::read_to_string(ctx.env_dir.join("teacup.env")).unwrap(),
        env_before
    );
    assert!(!ctx.env_dir.join("teacup.env.retired").exists());
    assert_no_secret_leak(&agent.secret_key().to_secret_hex(), &[&so, &se]);
}

#[test]
fn hard_failure_on_unreachable_relay_outside_dry_run() {
    let ctx = ctx();
    let (agent, _) = seed_provisioned(&ctx, "teacup", Some("ws://127.0.0.1:1"));
    let out = run_retire(&ctx, "teacup", &[]);
    assert!(
        !out.status.success(),
        "a real run must fail closed when the relay teardown cannot happen"
    );
    assert!(
        stderr(&out).contains("membership discovery failed"),
        "{}",
        stderr(&out)
    );
    // Fail-closed means fully intact state — a re-run after fixing the
    // network does the whole teardown.
    assert!(ctx.config_dir.join("creds/teacup.nsec").exists());
    assert!(ctx.env_dir.join("teacup.env").exists());
    assert!(ctx.env_dir.join("teacup.pub").exists());
    assert_no_secret_leak(
        &agent.secret_key().to_secret_hex(),
        &[&stdout(&out), &stderr(&out)],
    );
}

#[test]
fn already_retired_state_converges_without_relay_access() {
    let ctx = ctx();
    // Terminal host-half state: only the .env.retired archive remains.
    let agent = Keys::generate();
    let owner = Keys::generate();
    let attestation = buzz_sdk::nip_oa::compute_auth_tag(&owner, &agent.public_key(), "").unwrap();
    let retired = ctx.env_dir.join("teacup.env.retired");
    fs::write(
        &retired,
        format!(
            "# agent pubkey: {}\nBUZZ_RELAY_URL=ws://127.0.0.1:1\nBUZZ_AUTH_TAG={attestation}\n",
            agent.public_key().to_hex()
        ),
    )
    .unwrap();
    fs::set_permissions(&retired, fs::Permissions::from_mode(0o600)).unwrap();

    let out = run_retire(&ctx, "teacup", &[]);
    let so = stdout(&out);
    assert!(
        out.status.success(),
        "re-running retire on a retired agent must converge: {}",
        stderr(&out)
    );
    assert!(so.contains("already retired"), "{so}");
    // The owner-half command is reprintable from the archive alone.
    assert!(
        so.contains(&format!(
            "buzz-mint retire --agent {} --relay-url ws://127.0.0.1:1",
            agent.public_key().to_hex()
        )),
        "{so}"
    );
    // The archive itself is untouched and still 0600.
    assert!(retired.exists());
    assert_eq!(mode_of(&retired), 0o600);
}

#[test]
fn help_documents_the_ordering_contract() {
    for (bin, args) in [
        (bin().to_owned(), vec!["retire", "--help"]),
        (
            // buzz-mint sits in the same target dir as the test binary's bin.
            {
                let mut p = PathBuf::from(env!("CARGO_BIN_EXE_buzz-provision"));
                p.pop();
                p.join("buzz-mint").to_string_lossy().into_owned()
            },
            vec!["retire", "--help"],
        ),
    ] {
        if !Path::new(&bin).exists() {
            continue; // buzz-mint may not be built in this invocation
        }
        let out = Command::new(&bin).args(&args).output().unwrap();
        let so = stdout(&out);
        assert!(out.status.success(), "{bin} retire --help failed");
        assert!(
            so.contains("ORDERING CONTRACT"),
            "{bin} --help must carry the ⚑ ordering contract: {so}"
        );
        assert!(
            so.to_lowercase().contains("kind:0"),
            "{bin} --help must explain the kind:0 constraint: {so}"
        );
    }
}
